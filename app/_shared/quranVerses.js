const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";

export function toArabicDigits(n) {
  return String(n).replace(/\d/g, (d) => AR_DIGITS[d]);
}

// « سورة البقرة، الآية ١٥٣ » — la référence imprimée sous le verset.
export function verseReference(verse) {
  return `سورة ${verse.surah}، الآية ${toArabicDigits(verse.ayah)}`;
}

export function versesForThemes(themes) {
  const list = Array.isArray(themes) ? themes : [];
  return QURAN_VERSES.filter((v) => list.includes(v.theme));
}

export function verseById(id) {
  return QURAN_VERSES.find((v) => v.id === id) || null;
}

// Tirage uniforme sur les versets des thèmes choisis — pas d'abord un thème
// puis un verset, sinon un thème plus court serait sur-représenté.
export function pickVerse(themes, { exceptId } = {}) {
  const pool = versesForThemes(themes);
  const others = pool.length > 1 ? pool.filter((v) => v.id !== exceptId) : pool;
  return others.length ? others[Math.floor(Math.random() * others.length)] : null;
}
